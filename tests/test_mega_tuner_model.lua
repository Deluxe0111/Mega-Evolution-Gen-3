local Model = dofile("src/mega_tuner_model.lua")
local forms = dofile("data/mega_forms.lua")
local presentation = dofile("data/mega_presentation.lua")
local model = Model.new(forms, presentation)
assert(#model.forms == 98 and model:slug() == "mega_venusaur")
assert(model:countChanged() == 0)
assert(model:row().scale == 1)
local feet, base = model:row().feet, model:row().baseline
local x0, y0 = model:row().dx, model:row().dy
local fx0, fy0 = presentation.mega_venusaur.front.dx, presentation.mega_venusaur.front.dy
-- Direct D-pad movement changes only screen-space offsets.
assert(model:move(-1, 0))
assert(model:row().dx == x0-1)
assert(model:move(0, 1))
assert(model:row().dy == y0+1)
-- B+Up and B+Down use 0.05 scale steps (model is input-agnostic).
assert(model:scale(1))
assert(model:row().scale == 1.05)
assert(model:scale(-1))
assert(model:row().scale == 1)
assert(model:row().feet == feet and model:row().baseline == base)
assert(presentation.mega_venusaur.back.dx == x0)
assert(presentation.mega_venusaur.back.scale == 1)
model:toggleSide()
assert(model.side == "front" and model:row().scale == 1)
assert(model:move(1, -1))
assert(model:row().dx == fx0+1 and model:row().dy == fy0-1)
model:toggleShiny()
assert(model.shiny)
-- Same normal/shiny presentation when source geometry is identical.
assert(model:row().dx == fx0+1 and model:row().dy == fy0-1)
model:moveForm(13)
assert(model:slug() == "mega_mewtwo_x")
model:toggleSide()
assert(model:row().dy == 29)
model:scale(-1)
assert(model:row().scale == .95)
assert(model:countChanged() == 2)
local exported = model:exportLua()
local chunk,err = load(exported,"mega_export")
assert(chunk,err)
local check = chunk()
assert(check.mega_venusaur.back.dx == x0-1 and check.mega_venusaur.back.dy == y0+1)
assert(check.mega_venusaur.front.dx == fx0+1 and check.mega_venusaur.front.dy == fy0-1)
assert(check.mega_venusaur.back.feet == feet and check.mega_venusaur.back.baseline == base)
assert(check.mega_mewtwo_x.back.scale == .95)
assert(check.mega_mewtwo_x.back.dy == 29)
assert(exported:find("front_shiny = {",1,true))
local n=0
for slug,sides in pairs(check) do
  assert(sides.front and sides.back,slug)
  n=n+1
end
assert(n==98)
assert(model:exportLua()==exported,"non-deterministic export")
model:resetCurrent(presentation)
assert(model:countChanged()==1)
assert(model:row().scale==1 and model:row().dy==29)
print("PASS: d-pad offsets, B-modified scale, front/back independence, source anchors fixed, full 98-form export")
