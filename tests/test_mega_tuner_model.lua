local Model = dofile("src/mega_tuner_model.lua")
local forms = dofile("data/mega_forms.lua")
local presentation = dofile("data/mega_presentation.lua")
local model = Model.new(forms, presentation)
assert(#model.forms == 98, "complete roster required")
assert(model:slug() == "mega_venusaur")
assert(model:countChanged() == 0)
assert(model:row().scale == 1)
model.mode = "tune"
assert(model:adjust(-1))
assert(math.abs(model:row().scale - 0.95) < .0001)
assert(presentation.mega_venusaur.back.scale == 1, "must not mutate shipped table")
model:nextField(1)
assert(model:fieldName() == "dx")
model:adjust(1)
assert(model:row().dx == 1)
model:nextField(1)
assert(model:fieldName() == "dy")
model:adjust(1)
assert(model:row().dy == 1)
model:toggleSide()
assert(model.side == "front" and model:row().scale == 1)
model:nextField(3)
assert(model:fieldName() == "feet")
local feet = model:row().feet
model:adjust(-1)
assert(model:row().feet == feet - 1)
model:toggleShiny()
assert(model.shiny == true)
-- A form without separate shiny geometry deliberately shares the side row.
assert(model:row().feet == feet - 1)
model:moveForm(13)
assert(model:slug() == "mega_mewtwo_x")
assert(model:row().scale == 1)
model:toggleSide()
assert(model:row().dy == 4)
assert(model:countChanged() == 1)
model:nextField(2)
model:adjust(1)
assert(model:countChanged() == 2)
local exported = model:exportLua()
assert(exported:find("mega_mewtwo_x = {", 1, true))
assert(exported:find("mega_venusaur = {", 1, true))
assert(exported:find("scale = 0.95", 1, true))
assert(exported:find("dy = 5", 1, true))
assert(exported:find("front_shiny = {", 1, true)) -- source exceptions
local chunk,err = load(exported,"mega_export")
assert(chunk,err)
local check=chunk()
assert(check.mega_venusaur.back.scale == .95)
assert(check.mega_venusaur.back.dx == 1)
assert(check.mega_venusaur.back.dy == 1)
assert(check.mega_venusaur.front.feet == feet - 1)
assert(check.mega_mewtwo_x.back.dy == 5)
local n=0
for slug,sides in pairs(check) do
  assert(sides.back and sides.front,slug)
  n=n+1
end
assert(n==98, "export lost one or more Mega entries")
assert(exported == model:exportLua(), "export must be deterministic")
model:resetCurrent(presentation)
assert(model:countChanged() == 1)
assert(model:row().dy == 4)
print("PASS: calibrator edits 98 forms independently, preserves original data, and exports valid deterministic Lua")
